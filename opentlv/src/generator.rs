//! Reproducible wire cases from Core's deterministic generator
//! (`tlv_generate()`).

use std::fmt;
use std::ptr;

use opentlv_sys as native;

use crate::error::{Error, Result};
use crate::{FormatRef, Tag};

/// `size` zero bytes, or [`Error::OutOfMemory`] instead of aborting.
fn zeroed(size: usize) -> Result<Vec<u8>> {
    let mut bytes = Vec::new();
    bytes
        .try_reserve_exact(size)
        .map_err(|_| Error::OutOfMemory)?;
    bytes.resize(size, 0);
    Ok(bytes)
}

/// A candidate identifier and its inclusive Value size interval
/// (`tlv_generator_candidate_t`).
///
/// The Format classifies constructed identifiers, which receive generated
/// child streams; primitive Values contain arbitrary bytes. Leave out stream
/// terminators and identifiers that require contextual ordering. An empty
/// tag is the empty identifier, for Formats that accept one.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct GeneratorCandidate {
    /// The identifier.
    pub tag: Tag,
    /// Inclusive minimum Value size in bytes.
    pub min_value_size: usize,
    /// Inclusive maximum Value size in bytes.
    pub max_value_size: usize,
}

impl GeneratorCandidate {
    /// A candidate `tag` with Values of `min_value_size` to `max_value_size` bytes.
    pub fn new(tag: Tag, min_value_size: usize, max_value_size: usize) -> Self {
        GeneratorCandidate {
            tag,
            min_value_size,
            max_value_size,
        }
    }
}

/// Resource bounds of every generated case.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct GeneratorLimits {
    /// Positive total element bound, including parents.
    pub max_elements: usize,
    /// Maximum child depth; roots have depth zero; at most 64.
    pub max_depth: usize,
    /// Maximum Value size of every element in bytes.
    pub max_value_size: usize,
    /// Positive maximum size of a complete case in bytes; also the output
    /// capacity a case requires.
    pub max_case_size: usize,
}

/// Reproducible wire cases for property-based tests and fuzz corpora,
/// generated by Core's `tlv_generate()`.
///
/// Each case is one nonempty complete stream of candidate elements that
/// decodes and re-encodes byte-exactly through the Format; it is wire data,
/// not Schema- or Codec-valid content. The same [`Generator::VERSION`],
/// Format, candidates, limits, seed and case index produce the same bytes,
/// independent of earlier calls and of extra output capacity, so a failing
/// case is replayed from its index alone. Different seed or index pairs do
/// not guarantee different bytes.
///
/// Rust only stores the configuration; Core validates it and the Format's
/// read and write capability on every call, and performs all generation.
///
/// ```
/// use opentlv::{Format, Generator, GeneratorCandidate, GeneratorLimits, Reader, Tag};
///
/// let generator = Generator::new(
///     Format::Ber,
///     [
///         GeneratorCandidate::new(Tag::from_bytes(&[0x5a]), 0, 16),
///         GeneratorCandidate::new(Tag::from_bytes(&[0x70]), 0, 64),
///     ],
///     GeneratorLimits { max_elements: 8, max_depth: 2, max_value_size: 64, max_case_size: 512 },
///     1,
/// );
/// let case = generator.generate(42)?;
/// assert_eq!(generator.generate(42)?, case);
/// for element in Reader::with_format(&case, Format::Ber) {
///     element?;
/// }
/// # Ok::<(), opentlv::Error>(())
/// ```
pub struct Generator<'f> {
    format: FormatRef<'f>,
    candidates: Vec<GeneratorCandidate>,
    // Borrows the heap bytes of `candidates`' tags, which never move or change.
    raw_candidates: Vec<native::tlv_generator_candidate_t>,
    limits: GeneratorLimits,
    seed: u64,
}

// SAFETY: the raw table only borrows immutable bytes the generator owns, and
// the Format reference is itself `Send + Sync`.
unsafe impl Send for Generator<'_> {}
unsafe impl Sync for Generator<'_> {}

impl fmt::Debug for Generator<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Generator")
            .field("format", &self.format)
            .field("candidates", &self.candidates)
            .field("limits", &self.limits)
            .field("seed", &self.seed)
            .finish()
    }
}

impl Clone for Generator<'_> {
    fn clone(&self) -> Self {
        Generator::new(
            self.format,
            self.candidates.iter().cloned(),
            self.limits,
            self.seed,
        )
    }
}

impl<'f> Generator<'f> {
    /// Native algorithm version (`TLV_GENERATOR_VERSION`); record it with
    /// corpora, since a new version changes the generated bytes.
    pub const VERSION: u32 = native::TLV_GENERATOR_VERSION;

    /// Copies the ordered `candidates`, `limits` and `seed` (zero is valid)
    /// and borrows `format`. Nothing is validated until a case is requested.
    pub fn new(
        format: impl Into<FormatRef<'f>>,
        candidates: impl IntoIterator<Item = GeneratorCandidate>,
        limits: GeneratorLimits,
        seed: u64,
    ) -> Self {
        let candidates: Vec<GeneratorCandidate> = candidates.into_iter().collect();
        let raw_candidates = candidates
            .iter()
            .map(|candidate| native::tlv_generator_candidate_t {
                tag: candidate.tag.raw(),
                min_value_size: candidate.min_value_size,
                max_value_size: candidate.max_value_size,
            })
            .collect();
        Generator {
            format: format.into(),
            candidates,
            raw_candidates,
            limits,
            seed,
        }
    }

    /// The Format.
    pub fn format(&self) -> FormatRef<'f> {
        self.format
    }

    /// The ordered candidates.
    pub fn candidates(&self) -> &[GeneratorCandidate] {
        &self.candidates
    }

    /// The limits.
    pub fn limits(&self) -> GeneratorLimits {
        self.limits
    }

    /// The seed.
    pub fn seed(&self) -> u64 {
        self.seed
    }

    fn options(&self, case_index: u64) -> native::tlv_generator_options_t {
        native::tlv_generator_options_t {
            seed: self.seed,
            case_index,
            max_elements: self.limits.max_elements,
            max_depth: self.limits.max_depth,
            max_value_size: self.limits.max_value_size,
            max_case_size: self.limits.max_case_size,
            candidates: if self.raw_candidates.is_empty() {
                ptr::null()
            } else {
                self.raw_candidates.as_ptr()
            },
            candidate_count: self.raw_candidates.len(),
        }
    }

    /// Scratch bytes every case requires (`tlv_generator_workspace_size()`):
    /// `(max_depth + 1) * max_case_size`.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidArg`] for invalid limits or candidates, or when no
    /// candidate's minimum Value size fits both size limits;
    /// [`Error::Unsupported`] for a depth above 64; [`Error::Overflow`] when
    /// the workspace is not representable. The Format is not checked.
    pub fn workspace_size(&self) -> Result<usize> {
        let options = self.options(0);
        let mut size = 0usize;
        // SAFETY: the options borrow the live candidate table; `size` is writable.
        Error::check(unsafe { native::tlv_generator_workspace_size(&options, &mut size) })?;
        Ok(size)
    }

    /// Generates case `case_index` into new bytes of its exact size,
    /// allocating the output and workspace for the call.
    ///
    /// # Errors
    ///
    /// As for [`Generator::generate_into`], without capacity failures.
    pub fn generate(&self, case_index: u64) -> Result<Vec<u8>> {
        let workspace_size = match self.workspace_size() {
            Ok(size) => size,
            // tlv_generate() checks the Format before the configuration, so
            // let it report the failure; it fails before using any storage.
            Err(error) => {
                return Err(self
                    .generate_into(case_index, &mut [], &mut [])
                    .err()
                    .unwrap_or(error))
            }
        };
        let mut output = zeroed(self.limits.max_case_size)?;
        let mut workspace = zeroed(workspace_size)?;
        let written = self.generate_into(case_index, &mut output, &mut workspace)?;
        output.truncate(written);
        Ok(output)
    }

    /// Generates case `case_index` at the start of `output` with caller-owned
    /// scratch `workspace`, without allocating; returns the case size.
    ///
    /// `output` needs at least `max_case_size` bytes and `workspace` at least
    /// [`Generator::workspace_size`]; extra capacity does not change the
    /// case. Both may change even when generation fails.
    ///
    /// # Errors
    ///
    /// [`Error::Unsupported`] for a Format that cannot read and write or a
    /// depth above 64; the configuration errors of
    /// [`Generator::workspace_size`]; [`Error::BufferTooShort`] for too small
    /// output or workspace; [`Error::Limit`] if the bounded search finds no
    /// nonempty case; [`Error::Callback`] if the Format breaks its contract.
    pub fn generate_into(
        &self,
        case_index: u64,
        output: &mut [u8],
        workspace: &mut [u8],
    ) -> Result<usize> {
        let options = self.options(case_index);
        let mut written = 0usize;
        // SAFETY: the Format and the candidate table are live and immutable;
        // `output` and `workspace` are disjoint exclusive slices (empty ones
        // still have non-null addresses); `written` is writable.
        Error::check(unsafe {
            native::tlv_generate(
                self.format.raw(),
                &options,
                output.as_mut_ptr(),
                output.len(),
                workspace.as_mut_ptr(),
                workspace.len(),
                &mut written,
            )
        })?;
        Ok(written)
    }
}
